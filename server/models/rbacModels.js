const { DataTypes } = require('sequelize');
const { sequelize } = require('../config/db');
const { DEFAULT_TENANT_ID } = require('../config/defaultTenant');

// The single source of truth for "does user X hold role R over scope S".
// Teacher.role is a denormalized cache recomputed from this table (see
// services/roleCacheService.js) -- cheap for coarse checks/UI badges, but
// scope-sensitive authorization must query this table directly via
// requireScopedRole, never trust the cached string alone.
const UserRoleAssignment = sequelize.define('UserRoleAssignment', {
  id: {
    type: DataTypes.UUID,
    defaultValue: DataTypes.UUIDV4,
    primaryKey: true,
  },
  // We use string ID for userId to accommodate Clerk user IDs directly if needed, or local UUIDs
  userId: {
    type: DataTypes.STRING,
    allowNull: false,
  },
  role: {
    type: DataTypes.STRING,
    allowNull: false,
    comment: 'super_admin | dean | assistant_dean | coe | programme_coordinator | hod'
  },
  tenantId: {
    type: DataTypes.UUID,
    allowNull: false,
    defaultValue: DEFAULT_TENANT_ID,
  },
  teacherId: {
    type: DataTypes.STRING,
    allowNull: true,
    comment: 'Set once the person has a Teacher row; null before signup, when userId (email) is the only identity we have'
  },
  departmentId: {
    type: DataTypes.UUID,
    allowNull: true,
    comment: 'Scope assignment to a specific department'
  },
  sectionId: {
    type: DataTypes.UUID,
    allowNull: true,
    comment: 'Scope assignment to a specific section'
  },
  batchId: {
    type: DataTypes.STRING,
    allowNull: true,
    comment: 'Scope assignment to a specific batch (e.g. for programme_coordinator)'
  },
  schoolId: {
    type: DataTypes.UUID,
    allowNull: true,
    comment: 'Scope assignment to a specific school/faculty (e.g. for Dean)'
  },
  programId: {
    type: DataTypes.UUID,
    allowNull: true,
    comment: 'Reserved for a future program-wide scope; not used by any role today'
  },
  subjectId: {
    type: DataTypes.STRING,
    allowNull: true,
    comment: 'Scope assignment to a specific subject (e.g. for hod)'
  },
  semesterId: {
    type: DataTypes.STRING,
    allowNull: true,
    comment: 'Scope assignment to a specific semester offering (e.g. for hod)'
  },
  status: {
    type: DataTypes.ENUM('active', 'revoked'),
    allowNull: false,
    defaultValue: 'active',
    comment: 'Grants are revoked, never deleted -- audit trail'
  },
  source: {
    type: DataTypes.ENUM('manual', 'auto_split'),
    allowNull: false,
    defaultValue: 'manual',
    comment: 'Tags HOD grants generated by the auto-split rebalance service distinctly from manual assignment'
  },
  rebalanceId: {
    type: DataTypes.UUID,
    allowNull: true,
    comment: 'Ties an auto_split grant back to the HodRebalanceLog proposal that created it'
  },
  grantedBy: {
    type: DataTypes.STRING,
    allowNull: true,
  },
  grantedAt: {
    type: DataTypes.DATE,
    allowNull: true,
  },
  revokedBy: {
    type: DataTypes.STRING,
    allowNull: true,
  },
  revokedAt: {
    type: DataTypes.DATE,
    allowNull: true,
  }
}, {
  schema: 'users',
  timestamps: true,
});

module.exports = { UserRoleAssignment };
